# Definition for singly-linked list.
# class ListNode(object):
#     def __init__(self, x):
#         self.val = x
#         self.next = None

class Solution(object):
    def hasCycle(self, head):
        sr, fr = head, head
        
        while fr and fr.next:
            sr = sr.next
            fr = fr.next.next
            if sr == fr:
                return True
        return False

