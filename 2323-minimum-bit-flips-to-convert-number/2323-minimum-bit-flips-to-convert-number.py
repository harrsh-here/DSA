class Solution(object):
    def minBitFlips(self, start, goal):
        """
        :type start: int
        :type goal: int
        :rtype: int
        """
        ans = start^goal
        count = 0 
        while ans > 0:
            ans &= (ans - 1)  # Clears the rightmost set bit
            count += 1
        return count 

